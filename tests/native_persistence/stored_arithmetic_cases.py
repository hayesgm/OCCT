#!/usr/bin/env python3
"""Regenerate exact dyadic endpoint cases; no native floating arithmetic oracle."""
import argparse
import difflib
import sys
from fractions import Fraction
from pathlib import Path

SIGN = 1 << 63
MAX = 0x7fefffffffffffff

def value(bits):
    sign = -1 if bits & SIGN else 1
    exponent, mantissa = (bits >> 52) & 2047, bits & ((1 << 52) - 1)
    if exponent:
        mantissa += 1 << 52
    power = (exponent - 1023 - 52) if exponent else -1074
    return sign * Fraction(mantissa) * Fraction(2) ** power

def rounded(x):
    """Binary search exact ordered dyadics, then integer nearest/even choice."""
    negative = x < 0
    x = abs(x)
    if x > value(MAX):
        return None
    lo, hi = 0, MAX
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if value(mid) <= x:
            lo = mid
        else:
            hi = mid - 1
    floor = lo
    ceil = floor if value(floor) == x else floor + 1
    if floor == ceil:
        result = floor
    else:
        distance = x - value(floor)
        half = (value(ceil) - value(floor)) / 2
        result = floor if distance < half or (distance == half and floor % 2 == 0) else ceil
    return ((result | SIGN), (ceil | SIGN), (floor | SIGN)) if negative else (result, floor, ceil)

cases = []
def case(name, multiply, a, b):
    exact = value(a) * value(b) if multiply else value(a) + value(b)
    result = rounded(exact)
    refuse = result is None
    # The production enclosure deliberately refuses an infinite outward endpoint.
    refuse |= result is not None and result[0] & ~SIGN == MAX and a & ~SIGN != 0 and b & ~SIGN != 0
    r, low, high = result or (0, 0, 0)
    cases.append((name, multiply, a, b, r, low, high, refuse))

for sign in (0, SIGN):
    suffix = 'negative' if sign else 'positive'
    for mantissa in (0, 1, 2, 3, 0xfffffffffffff):
        case(f'minimum-normal-half-{mantissa}-{suffix}', True, sign | (0x0010000000000000 + mantissa), 0x3fe0000000000000)
    case('saved-square-' + suffix, True, sign | 0x1f675c4e89d655af, 0x1f675c4e89d655af)
    case('subnormal-endpoint-reuse-' + suffix, True, sign | 0x0000000221b7654f, 0x3ff0000000000000)
    case('smallest-endpoint-reuse-' + suffix, True, sign | 1, 0x3ff0000000000000)
    case('normal-boundary-product-' + suffix, True, sign | 0x0010000000000000, 0x3fefffffffffffff)
    case('underflow-half-tie-' + suffix, True, sign | 1, 0x3fe0000000000000)
    case('underflow-below-half-' + suffix, True, sign | 1, 0x3fdfffffffffffff)
    case('underflow-above-half-' + suffix, True, sign | 1, 0x3fe0000000000001)
    case('minimum-subnormal-below-' + suffix, True, sign | 1, 0x3fefffffffffffff)
    case('minimum-subnormal-above-' + suffix, True, sign | 1, 0x3ff0000000000001)
    case('three-half-subnormal-tie-' + suffix, True, sign | 3, 0x3fe0000000000000)
    case('saved-rounded-zero-square-' + suffix, True, sign | 0x1bd30c90d8277250, 0x1bd30c90d8277250)
    case('zero-times-normal-' + suffix, True, sign, 0x3ff0000000000000)
    case('zero-times-subnormal-' + suffix, True, sign, 1)
    case('normal-input-underflow-' + suffix, True, sign | 0x0010000000000000, 0x0010000000000000)
    case('overflow-' + suffix, True, sign | MAX, 0x4000000000000000)
    case('infinite-outward-product-' + suffix, True, sign | MAX, 0x3ff0000000000000)
    case('infinite-outward-sum-' + suffix, False, sign | MAX, sign | 0x0010000000000000)
    case('signed-subnormal-sum-' + suffix, False, sign | 1, sign | 2)
    case('normal-boundary-sum-' + suffix, False, sign | 0x000fffffffffffff, sign | 1)
    case('normal-difference-' + suffix, False, sign | 0x0010000000000001, (sign ^ SIGN) | 0x0010000000000000)
    case('normal-tie-sum-' + suffix, False, sign | 0x3ff0000000000000, sign | 0x3ca0000000000000)
    case('subnormal-cancellation-' + suffix, False, sign | 2, (sign ^ SIGN) | 2)
    case('normal-cancellation-' + suffix, False, sign | 0x0010000000000000, (sign ^ SIGN) | 0x0010000000000000)

# Preserve signed zero for genuine zero operands separately from nonzero
# products rounded to zero. The exact rational oracle has no signed-zero bit.
for a in (0, SIGN):
    for b in (0, SIGN):
        case(f'zero-pair-{a:x}-{b:x}', True, a, b)

lines = ['// Generated by stored_arithmetic_cases.py using exact Fraction dyadics.',
         'static const DyadicCase THE_CASES[] = {']
for name, multiply, a, b, r, low, high, refuse in cases:
    words = ', '.join(f'0x{x:016x}ULL' for x in (a, b, r, low, high))
    lines.append(f'  {{"{name}", {str(multiply).lower()}, {words}, {str(refuse).lower()}}},')
lines.append('};\n')
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='verify the committed table without writes')
args = parser.parse_args()
path = Path(__file__).with_suffix('.hxx')
expected = '\n'.join(lines)
if args.check:
    actual = path.read_text()
    if actual != expected:
        sys.stderr.writelines(difflib.unified_diff(actual.splitlines(keepends=True),
            expected.splitlines(keepends=True), fromfile=str(path), tofile='exact dyadic regeneration'))
        sys.exit(1)
    print('exact dyadic table matches regeneration')
else:
    path.write_text(expected)
